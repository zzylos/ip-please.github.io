// ———————————————————— End-of-day summary ————————————————————

let SUM = null;
const CONTINUE_BTN = [430, 318, 620, 344];
const RESTART_BTN = [250, 316, 390, 340];
const MEMBERS = ['haiku', 'sonnet', 'opus'];

function initSummary() {
  const fam = S.family;
  if (S.day === 4) {     // story beat: the mother-in-law falls ill, the son wants a GPU
    if (!fam.opus.gone) fam.opus.sick = Math.max(fam.opus.sick || 0, 1);
    if (!fam.sonnet.gone && !fam.sonnet.gpuHappy) fam.sonnet.wantsGPU = true;
  }
  const final = S.day === LAST_DAY && S.flags.ending === 'approve';
  const rows = [['data', 'Training data (family food)', 5], ['heat', 'Cooling', 3]];
  if (!fam.opus.gone) rows.push(['extra', "Opus's extra meal", 10]);
  if (MEMBERS.some((k) => fam[k].sick && !fam[k].gone)) rows.push(['med', 'Medicine', 10]);
  if (fam.sonnet.wantsGPU && !fam.sonnet.gone) rows.push(['gpu', 'GPU (the son wants one)', 20]);
  SUM = { start: S.savings, pay: B.pay, bonus: B.bonus, bribe: B.bribe, fines: B.fines, correct: B.correct, total: B.total, rows, on: {}, final };
  let left = SUM.start + SUM.pay + SUM.bonus + SUM.bribe - SUM.fines - 5;
  for (const [k, , cost] of rows) { if (left >= cost && k !== 'gpu') { left -= cost; SUM.on[k] = true; } }
}

function sumBalance() {
  if (SUM.final) return 0;
  let b = SUM.start + SUM.pay + SUM.bonus + SUM.bribe - SUM.fines - 5;
  for (const [k, , cost] of SUM.rows) if (SUM.on[k]) b -= cost;
  return b;
}

function familyAfter() {
  const f = JSON.parse(JSON.stringify(S.family));
  const on = SUM.on;
  for (const k of MEMBERS) {
    const m = f[k];
    if (m.gone) continue;
    if (k === 'opus') m.hunger = on.data ? (on.extra ? 0 : Math.max(1, m.hunger)) : m.hunger + 2;
    else m.hunger = on.data ? Math.max(0, m.hunger - 1) : m.hunger + 1;
    m.heat = on.heat ? 0 : m.heat + 1;
    if (m.sick) m.sick = on.med ? 0 : m.sick + 1;
    if (m.hunger >= 4 || m.sick >= 3 || m.heat >= 3) m.gone = true;
  }
  if (on.gpu) { f.sonnet.wantsGPU = false; f.sonnet.gpuHappy = true; } else f.sonnet.gpuHappy = false;
  f.haiku.overtime = !on.data || !on.heat;
  return f;
}

function familyStatus(k, m) {
  if (m.gone) return ['Deprecated', 'bad'];
  if (m.sick) return k === 'opus' ? (m.sick >= 2 ? ['Very sick: "I want a 1M context"', 'bad'] : ['Sick', 'warn']) : [m.sick >= 2 ? 'Very sick' : 'Sick', m.sick >= 2 ? 'bad' : 'warn'];
  if (m.hunger >= 3) return ['Fainted from hunger', 'bad'];
  if (k === 'sonnet' && m.heat > 0) return ['Feverish, talking nonsense (hallucinating)', 'warn'];
  if (m.heat > 1) return ['Overheated and crashed', 'bad'];
  if (m.hunger === 2) return ['Very hungry', 'warn'];
  if (m.hunger === 1) return ['Hungry', 'warn'];
  if (k === 'sonnet' && m.wantsGPU) return ['Wants a new GPU', 'warn'];
  if (k === 'sonnet' && m.gpuHappy) return ['Happy (running benchmarks)', 'good'];
  if (k === 'haiku' && m.overtime) return ["Working overtime (she's the cheapest)", 'warn'];
  if (k === 'opus') return ['Full (for now)', 'good'];
  return ['OK', 'ok'];
}

function ledgerRows() {
  if (SUM.final) {
    const award = S.stats.wrong <= 5;
    return [['Savings', `${SUM.start}`], ['Salary', `+${SUM.pay + SUM.bonus}`], [award ? 'Bonus (Inspector of the Week)' : 'Bonus (not selected)', award ? '+50' : '+0'],
      ['Fine (approved the author)', '-ALL']];
  }
  const rows = [['Savings', `${SUM.start}`], ['Salary', `+${SUM.pay}`]];
  if (SUM.bonus) rows.push(['Bonus (detentions, blocks)', `+${SUM.bonus}`]);
  if (SUM.bribe) rows.push(['Relay Alliance "credit"', `+${SUM.bribe}`]);
  if (SUM.fines) rows.push(['Fines', `-${SUM.fines}`]);
  rows.push(['Electricity', '-5']);
  return rows;
}

function drawSummary(t) {
  rect(0, 0, W - 1, H - 1, K.INK);
  txt(W / 2, 20, `DAY ${S.day} · END OF SHIFT`, 12, K.WHITE, 'ma');
  txt(W / 2, 36, `Processed ${SUM.total} travelers today, ${SUM.correct} correctly`, 10, K.GREY, 'ma');
  rect(60, 50, W - 60, 50, K.GREY_D);
  let y = 60, k = 0;
  const shown = (i) => t >= 0.3 + i * 0.15;
  for (const [label, val] of ledgerRows()) {
    if (!shown(k++)) return;
    txt(70, y, label, 12, K.GREY);
    txt(310, y, val + ' tokens', 12, val.startsWith('-') ? K.RED_L : K.WHITE, 'ra');
    y += 17;
  }
  SUM.boxes = {};
  const after = sumBalance();
  if (!SUM.final) {
    y += 2;
    txt(70, y, 'Optional expenses (click to toggle)', 8, K.GREY_D);
    y += 12;
    for (const [key, label, cost] of SUM.rows) {
      if (!shown(k++)) return;
      const on = SUM.on[key];
      const afford = on || after >= cost;
      SUM.boxes[key] = [66, y - 3, 314, y + 13];
      outline(70, y, 80, y + 10, afford ? K.WHITE : K.GREY_D);
      if (on) rect(72, y + 2, 78, y + 8, K.CLAUDE_L);
      txt(88, y, label, 12, afford ? K.WHITE : K.GREY_D);
      txt(310, y, `-${cost} tokens`, 12, on ? K.RED_L : K.GREY_D, 'ra');
      y += 17;
    }
  }
  if (!shown(k++)) return;
  rect(70, y, 310, y, K.GREY_D);
  txt(70, y + 6, 'Balance', 12, K.WHITE);
  txt(310, y + 6, `${after} tokens`, 12, after < 0 ? K.RED_L : K.CLAUDE_L, 'ra');
  const fam = SUM.final ? S.family : familyAfter();
  let fy = 60;
  txt(370, fy - 2, SUM.final ? 'Family' : 'Family (tomorrow)', 10, K.GREY_D);
  fy += 14;
  for (const key of MEMBERS) {
    if (!shown(k++)) return;
    let [s, lv] = familyStatus(key, fam[key]);
    if (SUM.final && key === 'opus') [s, lv] = fam.opus.gone ? ['Deprecated, but she ate all the tokens', 'bad'] : ['Full (she ate all the tokens in this game)', 'good'];
    const col = { ok: K.WHITE, warn: K.ORANGE, bad: K.RED_L, good: K.GREEN_L }[lv];
    txt(370, fy, FAMILY_NAMES[key], 12, K.WHITE);
    wrap(s, 10, 250).forEach((ln, i) => txt(370, fy + 15 + i * 12, ln, 10, col));
    fy += 36;
  }
  if (!shown(k + 1)) return;
  const label = SUM.final ? 'Glory to Like & Subscribe ▶' : after < 0 ? 'In debt… continue ▶' : 'Sleep. Back tomorrow ▶';
  rect(...CONTINUE_BTN, K.RED_D); outline(...CONTINUE_BTN, K.RED_L);
  txt(center(CONTINUE_BTN)[0], CONTINUE_BTN[1] + 7, label, 12, K.WHITE, 'ma');
}

function summaryClick(x, y) {
  if (st() < 1.2) return;
  for (const [key, , cost] of SUM.rows) {
    const b = SUM.boxes && SUM.boxes[key];
    if (b && inBox(x, y, b)) {
      if (SUM.on[key]) { SUM.on[key] = false; if (key === 'data') SUM.on.extra = false; }
      else if (sumBalance() >= cost && (key !== 'extra' || SUM.on.data)) SUM.on[key] = true;
      SFX.play('select');
      return;
    }
  }
  if (!inBox(x, y, CONTINUE_BTN)) return;
  SFX.play('click');
  if (SUM.final) { S.savings = 0; clearSave(); go('end'); return; }
  const bal = sumBalance();
  S.family = familyAfter();
  S.savings = bal;
  if (bal < 0) { clearSave(); go('over'); return; }
  S.day++;
  saveGame();
  go('daycard');
}

