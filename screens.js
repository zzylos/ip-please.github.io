const SAVE_KEY = 'ip-please-save-v1';
// Display names live here rather than in the save, so an old save never shows stale names
const FAMILY_NAMES = { haiku: 'Wife Haiku', sonnet: 'Son Sonnet', opus: 'Mother-in-law Opus' };

function newGame() {
  for (const k of Object.keys(S)) delete S[k];
  Object.assign(S, {
    day: 1, savings: 0,
    family: { haiku: { hunger: 0, heat: 0, sick: 0 }, sonnet: { hunger: 0, heat: 0, sick: 0 },
      opus: { hunger: 1, heat: 0, sick: 0 } },
    stats: { approve: 0, deny: 0, detain: 0, correct: 0, wrong: 0 },
    flags: {}, tut: {},
  });
}

function saveGame() {
  try { localStorage.setItem(SAVE_KEY, JSON.stringify(S)); } catch (e) { /* private browsing etc.: if it can't be saved, so be it */ }
}

function loadSave() {
  try {
    const s = JSON.parse(localStorage.getItem(SAVE_KEY) || 'null');
    return s && s.day > 1 && s.day <= LAST_DAY ? s : null;
  } catch (e) { return null; }
}

function clearSave() { try { localStorage.removeItem(SAVE_KEY); } catch (e) { /* same as above */ } }

