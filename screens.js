const TYPE_CPS = 30;   // typewriter speed of the intro / erased screens, in characters per second

function typeLines(paras) {
  const out = [];
  let t = 0.5;
  paras.forEach((para, pi) => {
    for (const s of para) { out.push({ pi, s, t }); t += [...s].length / TYPE_CPS + 0.12; }
    t += 0.6;
  });
  out.end = t + 1.3;
  out.npara = paras.length;
  return out;
}

